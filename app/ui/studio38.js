/**
 * Music Studio 3.9 playback presentation.
 * Repositions ORIGINAL track play buttons on their covers, preserving playback
 * handlers, metadata, deletion/undo and inspector click behavior.
 */
(() => {
  const audio = document.getElementById("studio34Audio");
  if (!audio || document.documentElement.dataset.studio39 === "ready") return;
  document.documentElement.dataset.studio39 = "ready";

  const containers = ["studio34FeedList", "tracksList"]
    .map(id => document.getElementById(id)).filter(Boolean);

  const songName = row => row.querySelector(".studio34-track-main strong")?.textContent?.trim()
    || row.dataset.filename || "трек";

  function activeFilename() {
    const src = audio.getAttribute("src");
    if (!src) return "";
    try {
      return decodeURIComponent(new URL(src, location.href).pathname.split("/").pop() || "");
    } catch {
      return "";
    }
  }

  function updatePlaybackVisuals() {
    const active = activeFilename();
    const playing = !!active && !audio.paused && !audio.ended;
    document.querySelectorAll(
      "#studio34FeedList .studio34-track-row, #tracksList .studio34-track-row"
    ).forEach(row => {
      const button = row.querySelector(".studio34-cover > .studio34-row-play");
      if (!button) return;
      const isActive = playing && row.dataset.filename === active;
      row.classList.toggle("studio39-playing", isActive);
      button.textContent = isActive ? "Ⅱ" : "▶";
      button.setAttribute("aria-label",
        (isActive ? "Пауза: " : "Воспроизвести: ") + songName(row));
      button.setAttribute("title",isActive ? "Пауза" : "Воспроизвести");
      button.setAttribute("aria-pressed", String(isActive));
    });
  }

  function enhanceRow(row) {
    const cover = row.querySelector(".studio34-cover");
    const play = row.querySelector(".studio34-row-play");
    if (!cover || !play) return;
    if (play.parentElement !== cover) cover.appendChild(play);
    if (row.dataset.studio39Ready !== "1") {
      row.dataset.studio39Ready = "1";
      cover.classList.add("studio39-playable-cover");
      cover.removeAttribute("aria-hidden");
      play.setAttribute("title","Воспроизвести трек");
    }
    // The single playback action lives on the cover, not in the swipe tray.
    row.querySelector(".micro36-swipe-play")?.remove();
  }

  function scanRows() {
    for (const container of containers) {
      container.querySelectorAll(".studio34-track-row").forEach(enhanceRow);
    }
    updatePlaybackVisuals();
  }

  for (const list of containers) {
    new MutationObserver(scanRows).observe(list,{childList:true});
  }
  // Future playing/paused/generated songs will retain the correct button state.
  for (const event of ["play","pause","ended","emptied","loadedmetadata"]) {
    audio.addEventListener(event,updatePlaybackVisuals);
  }
  scanRows();
})();
