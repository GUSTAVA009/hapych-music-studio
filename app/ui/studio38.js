"use strict";
/**
 * Music Studio 3.8: cohesive production UI.
 * Everything here only composes pre-existing controls; music generation, audio,
 * delete/restore, voice recording and track storage keep their original handlers.
 */
(() => {
  const $ = id => document.getElementById(id);
  const make = (tag, cls, text) => {
    const node = document.createElement(tag);
    if (cls) node.className = cls;
    if (text !== undefined) node.textContent = text;
    return node;
  };
  if (!$("page-create") || document.querySelector(".studio38-live")) return;
  document.body.classList.add("studio38-live");

  const navCreate=document.querySelector('.nav-item[data-page="create"]');
  if(navCreate){
    const icon=navCreate.querySelector(".nav-icon");
    navCreate.replaceChildren(icon,document.createTextNode("Создать трек"));
  }
  const navTracks=document.querySelector('.nav-item[data-page="tracks"]');
  if(navTracks){
    const icon=navTracks.querySelector(".nav-icon");
    navTracks.replaceChildren(icon,document.createTextNode("Библиотека"));
  }

  // Functional universal search. Return/Enter opens the real library search,
  // without interfering with the create-page search/filter or its pagination.
  const header=document.querySelector(".topbar");
  const search = make("label","studio38-global-search");
  search.setAttribute("aria-label","Поиск по библиотеке");
  search.innerHTML = '<svg aria-hidden="true" viewBox="0 0 24 24" width="19" height="19" fill="none" stroke="currentColor" stroke-width="1.8"><circle cx="10.8" cy="10.8" r="6.8"/><path d="m16 16 5 5"/></svg>';
  const input=make("input");
  input.type="search";input.id="studio38GlobalSearch";
  input.placeholder="Поиск по моим трекам…";
  input.setAttribute("aria-label","Поиск по моим трекам — Enter");
  search.append(input);
  if(header)header.insertBefore(search,$("backendBadge"));
  input.addEventListener("keydown",e=>{
    if(e.key!=="Enter")return;
    e.preventDefault();
    const query=input.value.trim();
    document.querySelector('.nav-item[data-page="tracks"]')?.click();
    const target=$("librarySearch");
    if(target){
      target.value=query;
      target.dispatchEvent(new Event("input",{bubbles:true}));
      target.focus({preventScroll:true});
    }
  });

  const creator=$("page-create");
  const edit=creator.querySelector(".studio37-editor");
  const title=edit?.querySelector(".studio37-title-card");
  const style=edit?.querySelector(".studio37-style-card");
  const lyrics=edit?.querySelector(".studio37-lyrics-card");
  const extras=$("studio37Extras");
  const tools=edit?.querySelector(".studio37-composer-toolbar");
  // The inspiration shows a first-class song title (optional and automatically
  // generated by the existing backend when empty), a style field and long lyrics.
  if (edit && title && style && lyrics && tools && extras) {
    tools.insertAdjacentElement("afterend",title);
    title.insertAdjacentElement("afterend",lyrics);
    lyrics.insertAdjacentElement("afterend",style);
    extras.querySelector(".studio37-extras-head span:first-child").textContent="Голос, темп и длительность";
    title.querySelector(".card-head h2").textContent="Название трека";
    style.querySelector(".card-head h2").textContent="Стиль и звучание";
    lyrics.querySelector(".card-head h2").textContent="Текст песни";
    edit.classList.add("studio38-composer");
  }
  const createdTitle=$("create-title");
  if(createdTitle)createdTitle.textContent="Создать трек ✦";
  const creationSub=creator.querySelector(".heading p");
  if(creationSub)creationSub.textContent="Сформулируй идею, опиши звучание и создай два варианта своей песни.";
  const composerHeading=creator.querySelector(".heading");
  if(composerHeading){
    const help=make("button","studio38-context-help","Как это работает?");
    help.type="button";
    help.addEventListener("click",()=>{
      const target=creator.querySelector("details.help-card");
      if(target){
        target.open=true;
        target.scrollIntoView({block:"nearest",behavior:"smooth"});
      }
    });
    composerHeading.append(help);
  }

  // Contextual creative hints use actual saved data and existing API endpoints.
  const feed=creator.querySelector(".studio34-feed");
  const feedTitle=feed?.querySelector(".studio34-feed-title h2");
  if(feedTitle)feedTitle.textContent="Последние композиции";
  const all=feed?.querySelector("#feedGoLibrary");
  if(all)all.textContent="Открыть библиотеку";
  // Avoid fake statistics; reflect only /api/tracks, /api/voices responses.
  const status=make("div","studio38-counts");
  status.setAttribute("aria-live","polite");
  if(feed && all)feed.querySelector(".studio34-feed-title")?.append(status);
  async function refreshCounts(){
    try{
      const [songs,voices]=await Promise.all([
        fetch("/api/tracks",{cache:"no-store"}).then(r=>r.ok?r.json():Promise.reject(Error("tracks"))),
        fetch("/api/voices",{cache:"no-store"}).then(r=>r.ok?r.json():Promise.reject(Error("voices")))
      ]);
      const n=Array.isArray(songs.tracks)?songs.tracks.length:0;
      const v=Array.isArray(voices.voices)?voices.voices.length:0;
      status.textContent=n+" треков · "+v+" голосовых записей";
      const libCount=$("studio38LibraryTotal");
      if(libCount)libCount.textContent=n+" сохранённых композиций";
      const vc=$("studio38VoiceCount");
      if(vc)vc.textContent=v+" записей";
    }catch(e){status.textContent="Локальная библиотека";}
  }

  // Music library: add a concise toolbar with real quick actions.
  const library=$("page-tracks");
  const libraryHeading=library?.querySelector(".heading");
  const librarySub=libraryHeading?.querySelector("p");
  if(librarySub)librarySub.textContent="Все готовые песни в одном месте — слушай, выбирай и возвращайся к любимым.";
  if(libraryHeading){
    const count=make("span","studio38-library-stat","");
    count.id="studio38LibraryTotal";
    libraryHeading.append(count);
  }
  const list=$("tracksList");
  const libTools=library?.querySelector(".library-toolbar");
  if(libTools){
    const label=make("span","studio38-library-sort-label","Быстрые действия");
    libTools.append(label);
    const reset=make("button","studio38-clean-button","Сбросить поиск");
    reset.type="button";
    reset.addEventListener("click",()=>{
      const input=$("librarySearch");
      if(input){input.value="";input.dispatchEvent(new Event("input",{bubbles:true}));input.focus();}
    });
    libTools.append(reset);
  }
  // Library title, album art and all existing pagination handlers are native.

  // Voice area: useful recording guidance displayed beside the real wizard CTA.
  const voicePage=$("page-voices");
  const hero=voicePage?.querySelector(".studio34-voice-hero");
  const voiceGrid=make("div","studio38-voice-intro");
  if(hero){
    hero.parentNode.insertBefore(voiceGrid,hero);
    voiceGrid.append(hero);
    const tips=make("section","studio38-voice-tips");
    tips.innerHTML='<div class="studio38-tips-title"><span aria-hidden="true">✦</span><h2>Как получить чистый голос</h2></div>';
    const tipsList=make("ul");
    [
      "Записывай 20–40 секунд в тихой комнате.",
      "Пой или говори своим естественным тембром.",
      "Держи одинаковое расстояние до микрофона.",
      "Обязательно прослушай запись перед сохранением."
    ].forEach(t=>tipsList.append(make("li","",t)));
    tips.append(tipsList);
    voiceGrid.append(tips);
  }
  const voicesCard=voicePage?.querySelector("#voicesList")?.closest(".card");
  if(voicesCard){
    const count=make("span","studio38-voice-count","");
    count.id="studio38VoiceCount";
    voicesCard.querySelector(".card-head")?.append(count);
  }

  // Settings: real status and storage, without reintroducing the user-removed
  // 'Animation settings' option.
  const settingsPage=$("page-settings");
  const settingsCards=settingsPage?.querySelector(".single-content");
  if(settingsCards){
    settingsCards.classList.add("studio38-settings-layout");
    const second=settingsCards.querySelectorAll(":scope > .card");
    if(second[0]){
      second[0].classList.add("studio38-engine-card");
      const header=second[0].querySelector(".section-row h2");
      if(header)header.textContent="Музыкальная модель";
    }
    if(second[1])second[1].classList.add("studio38-logs-card");
    const storage=make("section","card studio38-storage-card");
    const heading=make("div","studio38-storage-heading");
    heading.innerHTML='<span aria-hidden="true">▤</span><div><h2>Хранилище и экспорт</h2><p>Музыка и образцы голоса остаются на этом компьютере</p></div>';
    const records=make("div","studio38-storage-records");
    const root=make("div");
    root.append(make("span","","Готовые треки"),make("strong","","Music Studio / Мои треки"));
    const originals=make("div");
    originals.append(make("span","","Исходные записи"),make("strong","","Music Studio / Мой голос"));
    records.append(root,originals);
    const go=make("button","secondary-button","Открыть библиотеку");
    go.type="button";
    go.addEventListener("click",()=>document.querySelector('.nav-item[data-page="tracks"]')?.click());
    storage.append(heading,records,go);
    settingsCards.insertBefore(storage,second[1]||null);
    const foot=make("div","studio38-settings-note",
      "Музыка, обложки и голосовые записи сохраняются локально. Изменение оформления не затрагивает модель и исходные аудиофайлы.");
    settingsCards.append(foot);
  }
  const wizard=$("studio34VoiceWizard");
  if(wizard)wizard.classList.add("studio38-voice-modal");
  const lvl=$("studio34VocalLevels");
  if(lvl)lvl.classList.add("studio38-levels");

  // Display note in the footer describing precise local model behavior.
  const localBanner=document.querySelector(".sidebar-bottom p");
  if(localBanner)localBanner.textContent="Твои песни и голос остаются на компьютере. Без подписки.";
  refreshCounts();
  document.querySelectorAll('.nav-item[data-page="tracks"],.nav-item[data-page="voices"]').forEach(node=>
    node.addEventListener("click",refreshCounts)
  );
})();


